"""Generates src/AirPodsControl.Core/Bridge/MediaTekUsbIds.g.cs from drivers/bluetooth/btusb.c
(every quirks_table entry flagged BTUSB_MEDIATEK, i.e. the adapters this kernel can initialise).
Usage: python3 gen-mediatek-ids.py <linux-src> <output.cs>"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(f"{src}/drivers/bluetooth/btusb.c", encoding="utf-8").read()
ids = sorted({f"{v.lower()}:{p.lower()}" for v, p in
              re.findall(r"USB_DEVICE\(0x([0-9a-fA-F]{4}),\s*0x([0-9a-fA-F]{4})\),\s*\.driver_info\s*=\s*BTUSB_MEDIATEK", text)})
lines = ",\n".join(f'        "{i}"' for i in ids)
open(out, "w", encoding="utf-8", newline="\n").write(f"""// <auto-generated> kernel/gen-mediatek-ids.py from WSL2-Linux-Kernel drivers/bluetooth/btusb.c (+ kernel/patches) </auto-generated>
namespace AirPodsControl.Core.Bridge;

public static partial class MediaTekUsbIds
{{
    /// <summary>USB VID:PID pairs that btusb initialises with the MediaTek protocol ({len(ids)} entries).</summary>
    public static readonly IReadOnlySet<string> Known = new HashSet<string>(System.StringComparer.OrdinalIgnoreCase)
    {{
{lines}
    }};
}}
""")
print(f"{len(ids)} MediaTek ids -> {out}")
